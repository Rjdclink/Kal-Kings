-- Kal Kings independent Kalshi quantitative observations and audited decisions.
-- Observations alone never count as trades or settled profit.
CREATE TABLE IF NOT EXISTS kal_kings_market_observations (
  ticker TEXT NOT NULL,
  observed_at TIMESTAMPTZ NOT NULL,
  bid NUMERIC(10,4) NOT NULL CHECK (bid > 0 AND bid < 1),
  ask NUMERIC(10,4) NOT NULL CHECK (ask > 0 AND ask < 1),
  PRIMARY KEY(ticker,observed_at)
);
CREATE INDEX IF NOT EXISTS kal_kings_market_observations_recent
  ON kal_kings_market_observations (observed_at DESC);
CREATE TABLE IF NOT EXISTS kal_kings_quant_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticker TEXT NOT NULL,
  observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted BOOLEAN NOT NULL,
  reason TEXT NOT NULL,
  model_expected_dollars NUMERIC(18,6),
  model_tail_dollars NUMERIC(18,6),
  calibration_status TEXT NOT NULL,
  proposed_count NUMERIC(14,2)
);
CREATE INDEX IF NOT EXISTS kal_kings_quant_decisions_recent
  ON kal_kings_quant_decisions (observed_at DESC);
